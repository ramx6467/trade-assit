"""Provider-independent broker contract. No live adapter is configured in this release."""
from typing import Protocol

class BrokerAdapter(Protocol):
    broker_id: str
    async def get_authorization_url(self, state: str) -> str: ...
    async def handle_callback(self, code: str, state: str) -> None: ...
    async def get_profile(self) -> dict: ...
    async def get_funds(self) -> dict: ...
    async def get_positions(self) -> list[dict]: ...
    async def get_holdings(self) -> list[dict]: ...
    async def get_orders(self) -> list[dict]: ...
    async def get_order_history(self, order_id: str) -> list[dict]: ...
    async def get_order_status(self, order_id: str) -> dict: ...
    async def get_market_data(self, instrument_id: str) -> dict: ...
    async def subscribe_market_data(self, instrument_id: str) -> None: ...
    async def unsubscribe_market_data(self, instrument_id: str) -> None: ...
    async def validate_order(self, order: dict) -> dict: ...
    async def place_order(self, order: dict, idempotency_key: str) -> dict: ...
    async def cancel_order(self, order_id: str) -> dict: ...


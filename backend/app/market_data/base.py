"""Provider contract; providers return normalized data and never silently substitute symbols."""
from typing import Protocol

class MarketDataProvider(Protocol):
    provider_id: str
    def get_instruments(self) -> list[dict]: ...
    def get_historical_candles(self, symbol: str, timeframe: str, limit: int = 240) -> list[dict]: ...
    def get_latest_quote(self, symbol: str, timeframe: str = "15m") -> dict: ...

class StreamingMarketDataProvider(MarketDataProvider, Protocol):
    async def subscribe_quotes(self, symbol: str) -> None: ...
    async def unsubscribe_quotes(self, symbol: str) -> None: ...
